// ---------- .env.example ----------

export function generateEnvExample(files, report, changes) {
  const envVars = new Set(report.base44EnvVarReferences.map((v) => v.replace('VITE_BASE44_', 'VITE_APP_')));
  if (envVars.size === 0) return;
  const body =
    '# Generated by unvibe. These variables replace the Base44-branded ones\n' +
    '# the extractor left in the source code. Safe defaults included.\n\n' +
    [...envVars]
      .sort()
      .map((name) => `${name}=`)
      .join('\n') +
    '\n';
  files['.env.example'] = body;
  changes.push(`Generated .env.example with ${envVars.size} variable(s).`);
}

// ---------- helpers ----------

function inferProjectName(files) {
  try {
    const pkg = JSON.parse(readText(files['package.json']) ?? '{}');
    if (pkg.name && pkg.name !== 'base44-app') return pkg.name;
  } catch {
    // fall through
  }
  return 'Ejected App';
}

function inferProjectSlug(files) {
  return String(inferProjectName(files))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'ejected-app';
}

function readText(entry) {
  if (entry == null) return null;
  if (typeof entry === 'string') return entry;
  if (entry instanceof Uint8Array || Buffer.isBuffer?.(entry)) {
    return Buffer.from(entry).toString('utf8');
  }
  return null;
}

function readShimFile(name) {
  return readFileSync(resolve(SHIM_ROOT, name), 'utf8');
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
