// @unvibe/codemods-base44
//
// Pure, deterministic transforms that take a FileMap (as produced by
// @unvibe/detect) and return a new FileMap representing a clean,
// runnable project. The orchestrator is `transformProject`; individual
// step helpers are exported so they're easy to test in isolation.

import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { detectFromFileMap } from '@unvibe/detect';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SHIM_ROOT = resolve(__dirname, '../../../shim-lib/localDb/src');

/**
 * @typedef {import('@unvibe/detect').DetectionReport} DetectionReport
 */

/**
 * @typedef {Object} TransformOptions
 * @property {'localDb'} [target='localDb']    Which runtime shim to inject. Only localDb in v1.
 * @property {string}    [projectName]         Human-friendly name for package.json + README.
 * @property {string}    [projectSlug]         Slug used for the `name` field in package.json.
 */

/**
 * @typedef {Object} TransformResult
 * @property {import('@unvibe/detect').FileMap} files   Rewritten project tree.
 * @property {string[]} changes                               Human-readable summary of what was changed.
 * @property {DetectionReport} report                          Detection report used to drive the transforms.
 */

/**
 * Top-level orchestrator. Runs detection (if no report is provided), applies
 * every transform, and returns a new FileMap plus a change log suitable for
 * displaying to the user.
 *
 * @param {import('@unvibe/detect').FileMap} files
 * @param {TransformOptions} [options]
 * @returns {TransformResult}
 */
export function transformProject(files, options = {}) {
  const report = detectFromFileMap(files);
  const changes = [];
  const opts = {
    target: options.target ?? 'localDb',
    projectName: options.projectName ?? inferProjectName(files),
    projectSlug: options.projectSlug ?? inferProjectSlug(files),
  };

  /** @type {import('@unvibe/detect').FileMap} */
  const out = { ...files };

  transformPackageJson(out, opts, changes);
  transformViteConfig(out, changes);
  rewriteBase44Client(out, report, changes);
  injectLocalDbShim(out, report, changes);
  injectEntitiesModule(out, report, changes);
  transformAppParams(out, changes);
  transformIndexHtml(out, opts, changes);
  transformReadme(out, opts, report, changes);
  generateEnvExample(out, report, changes);

  return { files: out, changes, report };
}

// ---------- package.json ----------

export function transformPackageJson(files, opts, changes) {
  const raw = readText(files['package.json']);
  if (!raw) return;
  const pkg = JSON.parse(raw);

  for (const name of ['@base44/sdk', '@base44/vite-plugin']) {
    if (pkg.dependencies?.[name]) {
      delete pkg.dependencies[name];
      changes.push(`Removed \`${name}\` from package.json dependencies.`);
    }
    if (pkg.devDependencies?.[name]) {
      delete pkg.devDependencies[name];
      changes.push(`Removed \`${name}\` from package.json devDependencies.`);
    }
  }

  if (pkg.name === 'base44-app' || !pkg.name) {
    pkg.name = opts.projectSlug;
    changes.push(`Renamed package to \`${opts.projectSlug}\`.`);
  }

  files['package.json'] = JSON.stringify(pkg, null, 2) + '\n';
}

// ---------- vite.config.js ----------

const CLEAN_VITE_CONFIG = `import react from '@vitejs/plugin-react';
import { defineConfig } from 'vite';
import path from 'node:path';

// Generated by unvibe. The original vite.config.js called the
// \`@base44/vite-plugin\` which is no longer available post-ejection.

export default defineConfig({
  logLevel: 'error',
  plugins: [react()],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, './src'),
    },
  },
});
`;

export function transformViteConfig(files, changes) {
  if (!('vite.config.js' in files) && !('vite.config.ts' in files)) return;
  files['vite.config.js'] = CLEAN_VITE_CONFIG;
  delete files['vite.config.ts'];
  changes.push('Rewrote vite.config.js — dropped the @base44/vite-plugin call.');
}

// ---------- base44Client.js ----------

export function rewriteBase44Client(files, report, changes) {
  if (!report.base44Client.present) return;
  files['src/api/base44Client.js'] = readShimFile('base44Client.js');
  changes.push('Replaced the dead base44Client stub with a real re-export of the local runtime.');
}

// ---------- localDb shim + entity schemas ----------

export function injectLocalDbShim(files, report, changes) {
  files['src/lib/localDb.js'] = readShimFile('localDb.js');
  files['src/lib/_entitySchemas.generated.js'] = renderEntitySchemasModule(report);
  changes.push(
    `Injected src/lib/localDb.js (localStorage-backed) and _entitySchemas.generated.js with ${report.entities.length} entities.`,
  );
}

function renderEntitySchemasModule(report) {
  const schemas = Object.fromEntries(report.entities.map((e) => [e.name, e.schema]));
  return (
    '// Auto-generated by unvibe from the extractor entity schemas.\n' +
    '// Consumed by src/lib/localDb.js to build a typed local store.\n\n' +
    'export const entitySchemas = ' +
    JSON.stringify(schemas, null, 2) +
    ';\n'
  );
}

// ---------- src/api/entities.js ----------

export function injectEntitiesModule(files, report, changes) {
  if (report.entities.length === 0) return;
  const body =
    "// Generated by unvibe.\n" +
    "// Named exports for every entity the extractor discovered. Matches the\n" +
    "// import shape some Base44 apps use (`import { Card, Deck } from '@/api/entities'`).\n\n" +
    "import { entities } from '@/lib/localDb.js';\n\n" +
    report.entities
      .map((e) => `export const ${e.name} = entities.${e.name};`)
      .join('\n') +
    '\n';
  files['src/api/entities.js'] = body;
  changes.push(
    `Created src/api/entities.js with named exports for ${report.entities.length} entities.`,
  );
}

// ---------- app-params.js ----------

export function transformAppParams(files, changes) {
  const raw = readText(files['src/lib/app-params.js']);
  if (!raw) return;
  let next = raw;
  // Rename env vars VITE_BASE44_X → VITE_APP_X.
  next = next.replace(/\bVITE_BASE44_/g, 'VITE_APP_');
  // Strip the base44_ storage key prefix used for localStorage cache keys so
  // the ejected app isn't leaving breadcrumbs named after the old platform.
  next = next.replace(/base44_/g, 'app_');
  if (next !== raw) {
    files['src/lib/app-params.js'] = next;
    changes.push(
      'Rewrote src/lib/app-params.js to use VITE_APP_* env vars (was VITE_BASE44_*).',
    );
  }
}

// ---------- index.html ----------

export function transformIndexHtml(files, opts, changes) {
  const raw = readText(files['index.html']);
  if (!raw) return;
  // The extractor sometimes prepends a stray JS snippet before the `<!doctype>`
  // declaration; strip everything up to the first `<!doctype` or `<!DOCTYPE`.
  const doctypeIdx = raw.search(/<!doctype|<!DOCTYPE/);
  let next = doctypeIdx > 0 ? raw.slice(doctypeIdx) : raw;
  // Replace title.
  next = next.replace(
    /<title>[^<]*<\/title>/i,
    `<title>${escapeHtml(opts.projectName)}</title>`,
  );
  // Replace the Base44 favicon with a standard placeholder.
  next = next.replace(
    /<link rel="icon"[^>]*\/?>/i,
    '<link rel="icon" type="image/svg+xml" href="/favicon.svg" />',
  );
  if (next !== raw) {
    files['index.html'] = next;
    changes.push('Cleaned index.html — stripped extractor preamble, replaced title and favicon.');
  }
}

// ---------- README ----------

